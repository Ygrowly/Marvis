A[15] = ("必背", """**看门狗续期**：拿到锁后起后台线程，在 TTL 到期前不断续期（Redisson 的 watchLock），业务跑完再主动释放。

但**续期只是缓解，不是根治**——续期本身也可能因 GC 停顿 / 网络分区而中断。真正保证安全要靠 **fencing token**；另外把长业务改成**分批 + 每批重新抢锁**，把损失限制在一批内。""")

A[16] = ("必背", """因为**锁服务判断的是"时间"，而客户端的事实是"是不是还在跑"**，这两者会脱节：**GC 停顿**（线程停了但锁没停）、**时钟漂移**（本地时间不准）、**网络分区**（还活着但联系不上锁服务）。

所以 **TTL 没有安全值**：短了出现双持有者，长了可用性差，而"最长停顿"没有上界。结论：**安全性不能只靠锁服务对时间的判断，要搬到资源侧（fencing token）**。""")

A[17] = ("必背", """发锁时给一个**单调递增的号**（ZooKeeper / etcd 的 revision，或自增计数），客户端带着这个号去写资源，**资源侧只接受比已见过的最大号更大的写**。

解决的是"**旧持有者（其实已经过期）的写仍然被接受**"——即使锁服务判错了，资源侧也能拒掉。代价：**资源侧必须配合改造**（很多存储做不到），所以它是正确性的最后一道，不是默认配置。""")


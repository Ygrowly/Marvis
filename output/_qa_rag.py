A[9] = ("理解", """两件事叠加：**分层**给出对数级的搜索路径（100 万节点约 5–6 层，从最高层开始、走不动就下层）；**图上贪心导航**让每层只需和局部邻居比较。本质上是"**跳表的分层思想 + 图的近邻连接**"。

代价：构图时间与内存（邻居表）、以及它是**近似**的——召回率靠检索时的候选队列参数调。""")

A[10] = ("必背", """RRF（Reciprocal Rank Fusion）= 对每路结果的排名 r 取 `1/(k + r)` 再求和（k 常取 60）。

**为什么不直接加分数：两路分数量纲不可比**——余弦 ∈ [0,1]，BM25 无上界且随词频/文档长度浮动，直接相加等于让量纲大的那一路说了算；用排名就把这个变量消掉了。

k 的作用是**平滑高排名的差距**：k 越大，第 1 名和第 2 名的贡献差越小（`1/(k+1)` vs `1/(k+2)`）；k 太小会让"某一路单独第一"过于强势。""")

A[11] = ("必背", """**必须在检索层、先于召回**（ACL pre-filter），不能等召回到答案之后再过滤。五条：① 身份进入检索层、ACL 过滤先于召回；② **缓存按租户 / 权限分区**——缓存会绕过 ACL（有权用户查过的结果会命中给无权用户），所以分区不是优化，是**权限模型的一部分**；③ 引用和下载**再次鉴权**；④ 做**跨租户与撤权测试**；⑤ 日志避免记录敏感原文。""")

A[12] = ("必背", """收益要说清口径：Contextual Retrieval 的实验里，重排把检索失败率从 2.9% 降到 1.88%——**相对重排前降 35%，相对基线累计降 67%**，这两个数不能混。

代价是**延迟随候选数线性增长**（5 ms × N，重排 200 条就是 1 秒，比 ANN 召回慢两个数量级），所以常见折中是"召回几百 → 重排 50–100 → 进上下文 5–20"。而且**不一定值得**：精确编号、单跳事实这类查询召回本身已经排得很准，重排收益很小，**应通过 Eval 判断是否只在难题启用**。

原理：双塔把 query 和 doc 分别编码、编码时看不到对方，"除外""不适用"这类否定词被平均掉（结构性损失，换更大的双塔也补不回来）；交叉编码器把两者拼在一起，能看到逐词交互。""")

A[13] = ("理解", """**Recall@K**：正确证据有没有进前 K——回答"捞没捞到"，不关心顺序；**MRR**：第一个正确结果平均排在第几——回答"第一个对的来得多快"，适合单答案场景；**nDCG@K**：前 K 的排序质量——回答"排得准不准"，且支持分级相关性。

RAG 里检索层主要看 **Recall@K 和 nDCG@K**：召回阶段的目标是"不漏"，排序质量交给重排解决。""")

A[14] = ("必背", """按三个岔路口走：① 正确证据**进 TopK 了吗**（没进 → 召回问题）；② 进了 TopK 但**进最终 Context 了吗**（没进 → 重排 / 预算 / 去重 / 截断问题）；③ 都进了还是错 → **生成 / Prompt / 引用**问题。

前提是 **Trace 把候选、分数、重排位置、上下文版本都留下来了**，否则只能猜。另外要记住两层的损失是**相乘**的（Recall@20 95% × faithfulness 90% = 端到端上限 85.5%），所以端到端指标一定低于任何单层。""")

A[15] = ("必背", """三个动作：① **逐条绑定**——每句结论绑到具体片段，可定位到文档 / 章节 / **版本**；计算类结论还要绑定 SQL 或工具运行 ID，让用户能重跑；② **生成后回头验证**——把每条结论回原文找支撑，**找不到的直接撤掉**，因为"要求模型给引用"改的是概率，模型完全可以编一个看起来像引用的东西，**验证才是机制**；③ 代价要算——逐条验证让 token 成本接近翻倍（10 条结论约 8,500 token vs 生成 4,500 token），所以**只对高风险结论做**（金额、权限、生效时间）。

粗引用（文末列链接）的问题：把校验成本全推给读者，用户只能全信或全不信。""")

A[16] = ("必背", """五条：**没有召回足够证据**、**多个权威来源冲突**、**用户身份不足**、**超出知识库边界**、**时间 / 主体 / 口径不明确**。冲突时**不强行合成唯一答案**，而是显式返回证据（RuleArena 的做法）。

为什么拒答是设计的一部分：把"自信的错误"（代价 10 单位）换成"坦白的不知道"（1 单位），**总代价降到 1/10**——错误越贵，拒答越值钱。""")

A[17] = ("必背", """因为它们回答两个不同的问题——"证据有没有捞到" vs "答案对不对、有没有依据"，**混成一个数就两个都答不了**；分开之后才能算"提升哪一层更划算"。检索层看 Recall@K / nDCG@K；答案层看 Correctness / Faithfulness / Citation completeness / Answerability。

还有一条：**归因决定修复上限**——100 条失败里召回占 40、排序占 25、生成占 35，只换更强的模型最多修 35%。评测集要保留 holdout（真实案例：训练集打平、held-out 差 11.9 个点），规模按 `SE = √(p(1−p)/n)` 定：150 条约 ±3.4%，想分辨 2 个百分点需要约 900 条。""")

A[18] = ("理解", """因为**失败发生在三个不同地方**：① 证据没被捞到（召回）；② 捞到了没进上下文（重排 / 预算）；③ 进了还是答错（生成）。

检索失败率只覆盖①，而幻觉率主要是③的问题——证据就在上下文里，模型还是答错了或编了个引用。两者是**相乘关系**而不是同一个数（Recall 95% × faithfulness 90% = 端到端上限 85.5%），所以用检索指标冒充答案质量，会系统性地高估系统。""")

A[19] = ("必背", """六件套：**Source 事件触发增量解析与索引**（只重跑变化的 1%，100 万块每天改 1% 时省 **99%** 的嵌入调用）；**新旧索引双轨验证**；**文档和 chunk 版本化**；**删除 / 撤权必须传播**（索引内的块，加索引外的缓存与派生引用两层都要覆盖）；**回答记录知识版本**；**支持回滚 + 监控索引滞后**。

文档要带 `effective_at` / `expires_at` / `source_version`，回答要展示规则生效时间，冲突时**显式说明版本而不是偷偷选一个**。索引滞后（变更时刻 → 可检索时刻）必须是一个被监控的指标，超过承诺时限就是故障。""")

A[20] = ("理解", """**删除和撤权都要清两层**：**索引内**（删除按 `doc_id` 反查全部块，清向量 / 倒排 / 元数据，漏一个就是"已删内容还能被搜到"的合规事故）+ **索引外**（缓存、派生引用、Agent 记忆）——**缓存不接在主链路的过滤之后**，不清就会命中已删 / 已撤权的内容。

**删除按内容反查，撤权按主体反查**：删除难在缓存键是 query 文本、不是 `doc_id`（一条缓存里还拼了多个文档的块），所以要么给缓存条目记 provenance 后按 `doc_id` 反查失效、要么命中后回查"块还在吗"、要么版本号进缓存键整片失效；撤权靠缓存按租户 / 权限分区，但**分区只挡跨主体泄漏**——**同一用户被撤权后键没变，照样命中自己以前查到的内容**，所以**分区是结构，失效是动作，两个都要有**。**TTL 只是陈旧上界，不是生效保证**，合规删除不能拿它兜底。

换 Embedding 模型时：新旧向量不可比，必须全量重嵌入，且**不能原地替换**（没有回滚路径），要走**双写 + 影子索引 + 验证 + 切换**。""")

A[21] = ("理解", """**最新 / 私有 / 需要可引用的知识 → RAG**；**稳定的行为、格式、领域表达 → 可能微调**；**小而稳定的知识 → 长上下文可能更简单**（数据小、稳定、无权限差异、不需要溯源时，直接放长上下文更简单也可能更好）。

通常的顺序是：**先用 Prompt / RAG 建 Eval，再判断是否微调**——没有 Eval 就没法证明微调带来多少增益。决策由质量、成本、延迟、权限的评测驱动，不由架构偏好驱动。""")

A[22] = ("了解", """当问题必须靠**实体之间的关系**才能回答时（"A 公司的供应商里哪些同时是 B 的客户"这类多跳关联），纯向量检索拿不到这种结构信息，GraphRAG 才有增量。

代价是**构建与维护成本高**（抽实体、建图、图更新），而且它通常不是替代原有链路，而是作为**一路召回叠加**。所以判据是：先证明你的问题集里有相当比例是"关系型"的，再上；否则不值得。""")

A[23] = ("必背", """五条：① **身份进入检索层、ACL filter 先于召回**；② **缓存按租户 / 权限分区**（缓存会绕过 ACL）；③ **引用和下载再次鉴权**；④ 做**跨租户与撤权测试**（这两类测试是 RAG 特有的）；⑤ **日志避免记录敏感原文**。

再加一条工程习惯：评测集里要专门放**权限攻击样本**，否则你永远不知道越权到底有没有被拦住。""")

A[24] = ("理解", """**重排解决不了**——重排只是把已有候选重新排序，而多跳需要的候选**压根不在池子里**。

两条路：**Query Decomposition**（把一个多条件问题拆成多个子查询分别检索再合成）和 **Multi-hop 检索**（第二轮检索由第一轮发现的实体驱动——先检索"某公司 CEO"，再用找到的人名检索"母校"）。

本质上**这不是检索算法的问题，是查询规划的问题**。""")



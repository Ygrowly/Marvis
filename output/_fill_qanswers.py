A[37] = ("理解", """崩溃窗口指的是 2PC 的中间态被切断。① binlog 已落盘、redo 还停在 prepare 时崩溃：如果只看 redo 状态就回滚，而这个事务从库已经重放过了 → 从库多、主库少；② redo 已提交但 binlog 没写完：主库多、从库少。所以裁决依据必须是外部的完整性判据——binlog 完整就提交、不完整就回滚，不能让两边各按自己的日志判断。""")


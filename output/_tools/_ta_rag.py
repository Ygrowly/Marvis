A['G5'] = (
"""RAG 的失败发生在**三个不同地方**：① 证据没被捞到（召回）、② 捞到了没进上下文（重排 / 预算）、③ 进了还是答错（生成）。**端到端指标把它们混成一个数，所以定位不了问题**——这就是必须分层评测的原因。

检索层看 **Recall@K / nDCG@K**，答案层看 **Correctness / Faithfulness / Citation completeness / Answerability**。**两层的损失是相乘的**（Recall@20 95% × faithfulness 90% = 端到端上限 85.5%），所以端到端指标一定低于任何单层。

**归因决定修复上限**：100 条失败里如果召回占 40、排序占 25、生成占 35，**只换更强的模型最多修 35%**。评测集要**保留 holdout**（真实案例：训练集打平、held-out 差 11.9 个点），规模按 `SE = √(p(1−p)/n)` 定：150 条约 ±3.4%，想分辨 2 个百分点需要约 900 条。数据来源五类：真实高频问题、专家构造的边界、**线上 Bad Case**、**权限攻击样本**、**过期/冲突样本**——后三类是 RAG 特有的，测的是"该拒答时有没有拒答"。

排查顺序（检索好但答案差）：① 正确证据进 TopK 了吗 → 召回；② 进最终 Context 了吗 → 重排/预算/去重；③ 都进了还是错 → 生成/Prompt/引用。前提是 **Trace 把候选、分数、重排位置、上下文版本都留下来了**。""",
"""- **结论**：三段归因，检索层与答案层分开评；端到端指标一定低于任何单层。
- **推导链**：失败三段 → 分层指标 → 损失相乘 → 归因决定修复上限 → 三岔路排查。
- **量化**：Recall@20 95% × faithfulness 90% = 端到端上限 85.5%；150 条约 ±3.4%、分辨 2 个点需约 900 条；召回 40 / 排序 25 / 生成 35 时换模型最多修 35%。
- **边界与常见误解**：幻觉率不能用检索失败率代替（后者只覆盖漏召）；检索指标好而答案差，问题常出在"进没进上下文"这一层。""")


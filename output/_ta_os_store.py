STORE['S1'] = (
"""**OLTP 与 OLAP 的差别只有一个根因——数据在磁盘上怎么排。** **行存**把同一行的字段放在一起：**点查一次 IO 拿回整行、改写一行只碰一处**；但做聚合时**必须整行读进来再扔掉大部分字段**。**列存**把同一列的放在一起：**聚合只读用到的列**（100 列的表只取 2 列时 IO 差 60 倍以上），而且**同列同构所以压缩率高、数据连续所以能用向量化**；代价是**点查要拼 N 个列段、改一行要碰 N 个列段**——**这就是列存引擎的 UPDATE 普遍是异步按批的根本原因**。

选型三步：**① 先问访问模式**（点查 → 行存，聚合 → 列存）；**② 再问数据量**（千亿以下的行存大多够用，别一上来就上列存）；**③ 最后问维护成本**（两套存储 = 两套运维 + 一条同步链路）。

和 MySQL 侧呼应：冷热分离/归档解决的是"热查询背着冷数据跑"，而**分析型查询要隔离到列存或从库**，不能让它在主库上跑全表聚合。""",
"""- **结论**：根因是存储布局；行存利点查与改写，列存利聚合。
- **推导链**：布局 → 点查 vs 聚合的 IO 差异 → 列存 UPDATE 为什么按批 → 选型三步。
- **量化**：100 列取 2 列时 IO 差 60 倍以上。
- **边界与常见误解**："列存全面更好"×（点查和单行改写是它的短板）；数据量不大时用不上列存。""")


A[3] = ("必背", """**三段**：① **发送**（生产端发出去但 Broker 没收到 / 没确认）；② **存储**（Broker 收到但没持久化就挂了）；③ **消费**（消费者拿到了但没处理完就 ack）。

三段各有一道确认：生产端等 Broker 确认（`acks`）、Broker 持久化 + 多副本、消费端**处理完再 ack**。""")

A[4] = ("必背", """`acks` 三档：`0`（不等确认，最快也最容易丢）、`1`（等 Leader 写入，Leader 挂了可能丢）、**`all`（等 ISR 全部确认）**。

但 **`acks=all` 单独不保证不丢**——它指的是"ISR 里的所有副本"，ISR 缩到 1 时照样接受写。必须一起配：**`min.insync.replicas ≥ 2`**（ISR 不足就拒绝写，把"可能丢"换成"明确不可用"）+ **禁止从非 ISR 副本选主**。另外要有发送失败的回调与重试。""")

A[5] = ("必背", """**持久化 + 多副本**两层：消息落盘（顺序写保证吞吐），并复制到多副本。三个参数一起给才闭环：`acks=all` + `min.insync.replicas ≥ 2` + 不从落后副本选主。

必须接受的边界：**"不丢"的准确定义是"生产者收到成功 ack 的消息永不消失"**，不是"消息一定被处理一次"——后者要靠消费端与业务幂等。""")

A[6] = ("必背", """**处理成功之后再 ack**，顺序永远是"处理 → ack"。

不能"收到就 ack"——那是主动制造丢消息：提前 ack 后崩溃，Broker 认为已处理完不会再投，消息永久消失且无任何报警。""")

A[7] = ("理解", """因为 ack 的语义是"**这条我处理完了，可以删了**"。收到就 ack，等于在业务还没落地时就告诉 Broker 处理完了——此时进程崩溃，Broker 不会再投（它认为已完成），这条消息**永久消失且没有任何报警**。

正确顺序：处理成功 → ack；失败 → 不 ack（等重投），并进入重试队列 / 死信队列兜底。""")

A[8] = ("理解", """三档兜底：**重试**（限次 + 退避，不要无限重试）→ **重试队列**（RocketMQ 并发消费默认 16 次）→ **死信队列**。死信队列的意义是"**绝不静默丢弃**"——最后一定有人 / 有告警能看到。

配套一条：重试前先区分"可重试错误"与"业务条件不满足"，后者重试一万次也没用。""")

A[9] = ("必背", """本质是"**两个系统没法放进一个本地事务**"。三条路线：**事务消息**（RocketMQ 半消息 + Broker 回查本地事务状态）、**本地消息表**、**Outbox**（业务表与待发消息同事务落库，再由 Worker 投递）。

判据：Outbox 最通用（不依赖 MQ 特性），EnergyOps 用的就是它（Alarm 与 Notification Outbox 同事务）；RuleArena 明确"当前不提前引入 Kafka / Outbox"，升级条件是出现真实的跨服务事件投递需求。""")

A[10] = ("必背", """**跨进程通信没有"恰好一次"，框架只保证"至少一次"**。重复来自"处理"与"记录进度"无法原子化——三处来源（生产端重试、Broker 重投、消费端处理完但 ack 前崩溃）框架层都杜绝不了。

所以重复是"至少一次"的**代价**，由**业务幂等**吃掉。""")

A[11] = ("必背", """幂等 = 同一动作执行多次与执行一次效果相同。三类方案：**① 唯一约束**（数据库层面，最可靠，兜底用）；**② 查重表 / Redis 查重**（快，挡大多数，但不能只依赖它——Redis 挂了要让唯一约束兜底，**不要简单 fail open（会重复）或 fail closed（会全量积压）**）；**③ 状态机 / 条件更新**（天然幂等，如 `UPDATE ... WHERE status = 'INIT'`）。

关键：幂等键必须是**业务动作指纹**；而且**超时是"结果未知"**——要用同一个键重试，或先查下游权威状态，不要猜。""")

A[12] = ("必背", """用**业务动作指纹**：业务键 + 动作 + 目标 + 参数 + 版本 / 步骤。**不能用消息 ID 或 ToolCallID**——重投时它们会变，查重永远不命中。

粒度也要对到"**一次动作**"：只用订单号会把"创建"和"取消"混成一个键，反而把动作吃掉。""")

A[13] = ("必背", """**乱序来自"为了吞吐而并行"**：一个主题分成多个分区 / 队列，**不同分区之间不保证全局顺序**，同一分区内才有序。

另外两个来源：生产者侧——`enable.idempotence=false` 且 `in.flight > 1` 时，重试会让后发的先到；消费端——多线程并发处理同一个队列也会把顺序打乱（即使拉取是有序的）。""")

A[14] = ("必背", """**局部串行**：按业务键哈希到同一分区 / 队列，**通道内单线程消费、通道间并行**。

代价要会说：**保序的粒度就是并行的粒度**——单条 5 ms → 单分区 200 TPS，要 2000 TPS 就开 10 个分区，但**单键上限永远仍是 200 TPS**。

不能全局串行，因为那样吞吐被压到单通道速率。""")

A[15] = ("理解", """**会**（`enable.idempotence=false` 且 `in.flight > 1` 时）。正确配置：**开启幂等**（Kafka 3.0 起默认）+ `acks=all` + **`in.flight ≤ 5`**，既保序又不丢吞吐；`in.flight=1` 是保序但牺牲吞吐的退路。""")

A[16] = ("理解", """**保不住**。即使拉取是顺序的，多线程并发处理会让完成顺序随机。

要保证顺序，必须**同一通道单线程消费**（或按业务键做本地串行队列）——这就是"顺序 vs 吞吐"的取舍：想要顺序，就要接受单通道的速率上限。""")

A[17] = ("必背", """积压是一个减法：`净消解速率 = min(消费者数, 分区数) × 单消费者速率 − 生产速率`。

处理顺序：**先查根因，再扩容**。根因通常是"每件活变慢"（下游 DB 慢、某条消息卡住、GC、限流），此时加消费者只是让更多线程一起去撞慢点；确认是"量真的涨了"，再加消费者（且要先加分区）。""")

A[18] = ("必背", """**同一分区同一时刻只能被一个消费者消费**，所以消费能力的天花板是**分区数 × 单消费者速率**，多出来的消费者全闲置。

要扩容必须**先加分区**（代价：数据迁移、顺序语义可能变化），再加消费者。""")

A[19] = ("理解", """两条：① **临时 Topic + 搬运程序**——把积压消息快速转发到分区数更多的临时 Topic，用更多消费者并行消费，处理完再切回；② 业务允许的话，**先导出备份再跳过**（跳过不可逆，必须留备份）。

判据是业务决定不是技术决定：监控 / 埋点类可以跳，涉及钱和状态变更的不行。""")

A[20] = ("必背", """**三层递进**：**多副本**（数据不只一份）→ **能自动选主**（副本挂了有人顶上）→ **客户端知道新地址**（路由感知 / 元数据刷新），**缺一层都等于没有**。

选举策略上"只从 ISR 选"是**用可用性换不丢数据**（ISR 全挂则分区不可用）。而"MQ 永不挂"是伪目标——正确的兜底是让"MQ 不可用"成为被设计过的状态：降级、本地缓冲 / Outbox、幂等补发、可观测。""")

A[21] = ("必背", """ISR（In-Sync Replicas）是**与 Leader 保持同步的副本集合**。

允许从非 ISR 副本选主（unclean election）会**丢数据**——那个副本落后一截，它当上 Leader 后，落后区间的消息就"从未存在过"。所以生产要禁止 unclean 选举：**宁可这个分区暂时不可用，也不丢数据**；再配 `min.insync.replicas ≥ 2`，把"可能丢"换成"明确不可用"。""")

A[22] = ("必背", """五个：**吞吐**、**Topic 数量**（Kafka 适合少量大 Topic，RocketMQ 适合多 Topic）、**顺序与回溯**（能不能按业务键保序、按时间点重放）、**高级特性**（事务消息、延迟消息、死信队列）、**团队栈与运维能力**。

选最匹配约束的，MVP 阶段甚至可能不需要 MQ。""")

A[23] = ("理解", """四条：**顺序写**（磁盘顺序写接近内存随机写的量级）、**批量**（攒批发送与压缩，减少 IO 次数）、**零拷贝**（sendfile，数据不绕用户态）、**分区并行**（吞吐随分区横向扩展）。再加一条：消息只追加、不原地修改，读也是顺序读。""")

A[24] = ("理解", """判据是"**消费速率该由谁控制**"。**Pull**（Kafka）：消费者按自己能力拉，能批量、能重放，但要做长轮询避免空转、实时性受拉取间隔影响。**Push**（RabbitMQ 默认）：消息来了就推，延迟低，但推得快会把慢消费者压垮，需要 prefetch / 流控。

所以：消费者能力差异大、要批量重放 → Pull；延迟敏感、消费能力均匀 → Push。""")

A[25] = ("理解", """Kafka 存在内部主题 **`__consumer_offsets`**（默认 50 分区、压缩、多副本）。

**自动提交**（默认每 5 秒）的风险是**和业务处理进度脱钩**——可能丢（提交跑在处理前）也可能重复；**手动提交**分同步（可靠但阻塞）和异步（快但不重试，可能丢 offset）。

生产常见组合：**热路径异步提交 + 关闭 / 重平衡时同步兜一次**。""")

A[26] = ("了解", """可以理解为两种模式：**进度条模式**（Kafka / RocketMQ 用 offset：提交一个位点代表"这个位置之前的都处理完了"，天然批量，但要求通道内顺序推进）；**单据签收模式**（RabbitMQ 用 per-message ack：每条单独确认，可以乱序确认、可以批量，失败重投的位置更细）。

差别带来的后果：进度条模式下"跳过一条"会影响后面的位点推进；单据模式下可以精确 reject / 重投单条。""")



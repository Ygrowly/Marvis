LOCK['L1'] = (
"""乐观锁和悲观锁不是"快慢"之别，而是**把代价花在不同地方**：**悲观锁在动手前排队**（并发被压成串行，但不浪费工作），**乐观锁在提交时校验**（并发不受限，但冲突时白干）。

判据可以算：**期望尝试次数 = 1/(1−冲突率 p)**——p = 10% 只要 1.11 次；p = 50% 就要 2 次（等于白干一遍）；p = 90% 要 10 次。所以**冲突率低用乐观**，冲突率过半或重试代价很高或临界区本身很短时换悲观。**顺序上：先想能不能改成条件更新，再想缩临界区，最后才换锁**。

数据库里两种实现：**版本号**（`UPDATE ... SET ..., version = version + 1 WHERE id = ? AND version = N`，看影响行数）和**条件更新**（`UPDATE ... SET n = n − 1 WHERE id = ? AND n ≥ 1`）。**最好的答案往往既不是乐观也不是悲观，而是条件更新**——把判断和写入合成一条原子语句，**不排队也不重试**。

一个关键纠正：**乐观锁在数据库里同样要拿行锁**，只是只拿一条语句的时间——**真正的差别是持锁时间**。失败处理：**限次（2–3 次）+ 指数退避 + 抖动**，先区分"版本冲突"与"业务条件不满足"（后者重试一万次也没用）。""",
"""- **结论**：代价位置不同；判据 `1/(1−p)`；最好答案是条件更新而不是乐观/悲观二选一。
- **推导链**：排队 vs 校验 → 期望尝试次数 → 换锁的三个条件 → 实现（版本号/条件更新）→ 失败重试的纪律。
- **量化**：p=10% → 1.11 次、p=50% → 2 次、p=90% → 10 次；高冲突下乐观 N² vs 悲观 N。
- **边界与常见误解**："乐观锁不加锁"×（差别在持锁时间）；"先查再改 + 事务"防不住并发窗口；单条 UPDATE 不易死锁，但事务里多行且加锁顺序不同照样会。""")

LOCK['L2'] = (
"""锁的粒度不是在"性能"和"开销"之间选，而是在**冲突率**和**记账开销**之间选——粒度太细会让锁对象变多、记账（获取/释放、内存、死锁检测）变贵，甚至超过省下的等待。

**分段锁（striping）把冲突率降到约 1/N**：p = 40% 分 16 段后，期望尝试次数从 1.67 降到 1.03。但前提是**访问均匀分散**——**热键始终落在同一段，分段救不了它**，得换方案（本地聚合 / 队列串行 / 每节点累加）；而且段数不能大到记账反超收益。

**自旋还是睡眠由一个比值决定**：等待时间 vs "挂起 + 唤醒"约 2 μs 的成本——临界区不到 1 μs 就自旋，毫秒级必须睡；工程上常用"先自旋一小会儿再睡"。

**读写锁在读多写少时不一定更快**：临界区极短时它的记账（读计数、写者状态、升级判断）可能比省下的等待还贵，还有写者饥饿；"读多写少"的第一选择通常是**让读不参与竞争**（MVCC / 快照 / 读副本）。

**CAS 把乐观并发下沉到指令层**，三个边界：**ABA**（值 A→B→A，CAS 看不出；解法是把版本号一起 CAS）、**高竞争时退化成自旋烧 CPU**（这时加锁更好）、**一次只能保护一个变量**。**最优先的动作永远是减少竞争本身**。""",
"""- **结论**：粒度在冲突率与记账之间权衡；分段锁约降 1/N，但救不了热键。
- **推导链**：记账 vs 等待 → 分段效果与前提 → 自旋/睡眠的 2 μs 判据 → 读写锁的记账成本 → CAS 的三个边界。
- **量化**：p=40% 分 16 段 → 期望次数 1.67 → 1.03；挂起+唤醒约 2 μs。
- **边界与常见误解**："无锁一定更快"×（高竞争时空转烧 CPU）；"读写锁读多写少必胜"×（临界区极短时反而更慢）。""")

